export type TranslationKey = keyof typeof translations.en;

/**
 * Composable that returns a reactive `t` function for translating strings.
 * Reads the current language from the settings store.
 */
export function useI18n() {
  const settings = useSettingsStore();

  const lang = computed<Language>(() => (settings.settings.language as Language) ?? 'en');

  function t(key: TranslationKey): string {
    const dict = translations[lang.value] ?? translations.en;
    return (dict as Record<string, string>)[key] ?? (translations.en as Record<string, string>)[key] ?? key;
  }

  return { t, lang };
}
