export type TranslationKey = keyof typeof translations.en;

/**
 * Composable that returns a reactive `t` function for translating strings.
 * Reads the current language from the settings store.
 */
export function useI18n() {
  const settings = useSettingsStore();

  const lang = computed<Language>(() => (settings.settings.language as Language) ?? 'en');

  function t(key: TranslationKey): string {
    const dict = translations[lang.value] ?? translations.en;
    return (dict as Record<string, string>)[key] ?? (translations.en as Record<string, string>)[key] ?? key;
  }

  return { t, lang };
}

/**
 * Übersetzung außerhalb von Komponenten (Stores, Clients). Fällt ohne aktive Pinia-Instanz
 * (z. B. in Unit-Tests) auf Englisch zurück. `{name}`-Platzhalter werden ersetzt.
 */
export function tr(key: TranslationKey, vars: Record<string, string | number> = {}): string {
  let lang: Language = 'en';
  try {
    lang = (useSettingsStore().settings.language as Language) ?? 'en';
  } catch {
    /* keine Pinia → en */
  }
  const dict = (translations[lang] ?? translations.en) as Record<string, string>;
  const text = dict[key] ?? (translations.en as Record<string, string>)[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}
